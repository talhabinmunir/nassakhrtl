    public static List<string> Graphemes(string s) {
        List<string> outp = new List<string>();
        foreach (char c in s) {
            if (outp.Count > 0 && IsTransparent(c)) outp[outp.Count - 1] += c;
            else outp.Add(c.ToString());
        }
        return outp;
    }

    static string VisualLine(string line) {
        if (!RtlLine.IsMatch(line)) return line;
        List<KeyValuePair<bool, string>> segs = new List<KeyValuePair<bool, string>>();
        int last = 0;
        foreach (Match m in LtrRun.Matches(line)) {
            if (m.Index > last) segs.Add(new KeyValuePair<bool, string>(false, line.Substring(last, m.Index - last)));
            segs.Add(new KeyValuePair<bool, string>(true, m.Value));
            last = m.Index + m.Length;
        }
        if (last < line.Length) segs.Add(new KeyValuePair<bool, string>(false, line.Substring(last)));
        segs.Reverse();
        StringBuilder sb = new StringBuilder();
        foreach (KeyValuePair<bool, string> seg in segs) {
            if (seg.Key) { sb.Append(seg.Value); continue; }
            List<string> gs = Graphemes(seg.Value);
            gs.Reverse();
            foreach (string g in gs) {
                if (g.Length == 1) {
                    char mc;
                    if (Mirror.TryGetValue(g[0], out mc)) { sb.Append(mc); continue; }
                }
                sb.Append(g);
            }
        }
        return sb.ToString();
    }

    public static string ToVisual(string text) {
        string[] lines = text.Replace("\r\n", "\n").Split('\n');
        for (int i = 0; i < lines.Length; i++) lines[i] = VisualLine(lines[i]);
        return string.Join("\r\n", lines);
    }

    static string StripSet(string s, string setDesc, ref int count) {
        // setDesc: pairs of range chars "lo hi lo hi ..."
        StringBuilder sb = new StringBuilder();
        foreach (char c in s) {
            bool drop = false;
            for (int i = 0; i + 1 < setDesc.Length; i += 2) {
                if (c >= setDesc[i] && c <= setDesc[i + 1]) { drop = true; break; }
            }
            if (drop) count++;
            else sb.Append(c);
        }
        return sb.ToString();
    }

    public static bool LooksConverted(string s) {
        bool pres = false, baseLetter = false;
        foreach (char c in s) {
            if ((c >= '\uFB50' && c <= '\uFDFD') || (c >= '\uFE70' && c <= '\uFEFC')) pres = true;
            else if (c != '\u0640' && Forms.ContainsKey(c)) baseLetter = true;
        }
        return pres && !baseLetter;
    }

    public static FixResult Convert(string text, FixOptions o) {
        string t = text;
        int nHidden = 0, nSpell = 0, nPunct = 0, nDigits = 0, nDia = 0, nTat = 0, nShape = 0;

        // ZWNJ/ZWJ are NOT stripped here: in Persian/Urdu they legitimately
        // break or force joining, so they must influence shaping first.
        if (o.RemoveZeroWidth) {
            t = StripSet(t, "\u200B\u200B\u200E\u200F\u202A\u202E\u2066\u2069\uFEFF\uFEFF", ref nHidden);
        } else {
            // direction marks always go - they corrupt visual order silently
            int dummy = 0;
            t = StripSet(t, "\u200E\u200F", ref dummy);
        }
        if (o.NormalizeAlef) {
            StringBuilder sb = new StringBuilder();
            foreach (char c in t) {
                if (c == '\u0622' || c == '\u0623' || c == '\u0625' || c == '\u0671') { sb.Append('\u0627'); nSpell++; }
                else sb.Append(c);
            }
            t = sb.ToString();
        }
        if (o.NormalizeYaTa) {
            StringBuilder sb = new StringBuilder();
            foreach (char c in t) {
                if (c == '\u0649') { sb.Append('\u064A'); nSpell++; }
                else if (c == '\u0629') { sb.Append('\u0647'); nSpell++; }
                else sb.Append(c);
            }
            t = sb.ToString();
        }
        if (o.PunctToLatin) {
            StringBuilder sb = new StringBuilder();
            foreach (char c in t) {
                if (c == '\u060C') { sb.Append(','); nPunct++; }
                else if (c == '\u061B') { sb.Append(';'); nPunct++; }
                else if (c == '\u061F') { sb.Append('?'); nPunct++; }
                else sb.Append(c);
            }
            t = sb.ToString();
        }
        if (o.WesternDigits) {
            StringBuilder sb = new StringBuilder();
            foreach (char c in t) {
                if (c >= '\u0660' && c <= '\u0669') { sb.Append((char)('0' + (c - '\u0660'))); nDigits++; }
                else if (c >= '\u06F0' && c <= '\u06F9') { sb.Append((char)('0' + (c - '\u06F0'))); nDigits++; }
                else if (c == '\u066A') { sb.Append('%'); nDigits++; }
                else sb.Append(c);
            }
            t = sb.ToString();
        }
        if (o.RemoveDiacritics) {
            t = StripSet(t, "\u064B\u065F\u0670\u0670\u05B0\u05BC\u05C1\u05C2\u05C7\u05C7", ref nDia);
        }
        if (o.RemoveTatweel) {
            t = StripSet(t, "\u0640\u0640", ref nTat);
        }
        int nWrap = 0;
        if (o.WrapWidth > 0) t = WrapLines(t, o.WrapWidth, ref nWrap);

        string shaped = Reshape(t, out nShape);
        // ZWNJ/ZWJ have done their joining work during shaping; drop them now
        if (o.RemoveZeroWidth) shaped = StripSet(shaped, "\u200C\u200D", ref nHidden);
        else { int dummy2 = 0; shaped = StripSet(shaped, "\u200C\u200D", ref dummy2); }
        FixResult r = new FixResult();
        r.Text = ToVisual(shaped);

        List<string> parts = new List<string>();
        if (nShape > 0) parts.Add(nShape.ToString() + " letters shaped");
        if (nDigits > 0) parts.Add(nDigits.ToString() + " digits");
        if (nHidden > 0) parts.Add(nHidden.ToString() + " hidden chars removed");
        if (nDia > 0) parts.Add(nDia.ToString() + " diacritics removed");
        if (nTat > 0) parts.Add(nTat.ToString() + " tatweel removed");
        if (nPunct > 0) parts.Add(nPunct.ToString() + " punctuation");
        if (nSpell > 0) parts.Add(nSpell.ToString() + " letters normalized");
        if (nWrap > 0) parts.Add(nWrap.ToString() + " line breaks added");
        r.Total = nShape + nDigits + nHidden + nDia + nTat + nPunct + nSpell + nWrap;
        r.Summary = parts.Count == 0 ? "no RTL letters found" : string.Join(", ", parts.ToArray());
        return r;
    }

    // hard-break long lines at word boundaries (logical order, pre-shaping)
    public static string WrapLines(string text, int width, ref int count) {
        string[] lines = text.Replace("\r\n", "\n").Split('\n');
        List<string> outp = new List<string>();
        foreach (string line in lines) {
            if (line.Length <= width) { outp.Add(line); continue; }
            int pos = 0;
            while (line.Length - pos > width) {
                int searchFrom = Math.Min(pos + width, line.Length - 1);
                int brk = line.LastIndexOf(' ', searchFrom);
                if (brk <= pos) brk = pos + width; // single word longer than width
                outp.Add(line.Substring(pos, brk - pos).TrimEnd());
                count++;
                pos = brk;
                while (pos < line.Length && line[pos] == ' ') pos++;
            }
            outp.Add(line.Substring(pos));
        }
        return string.Join("\n", outp.ToArray());
    }

    public static string Restore(string text) {
        string reversed = ToVisual(text);
        StringBuilder sb = new StringBuilder();
        foreach (char c in reversed) {
            string b;
            if (Inverse.TryGetValue(c, out b)) sb.Append(b);
            else sb.Append(c);
        }
        return sb.ToString();
    }

