            if (hkClip) UnregisterHotKey(Handle, HK_CLIPBOARD);
            if (hkFix) UnregisterHotKey(Handle, HK_FIXBOX);
            if (hkRestore) UnregisterHotKey(Handle, HK_RESTOREBOX);
        } catch (Exception) { }
