    public static string Inspect(string grapheme) {
        if (string.IsNullOrEmpty(grapheme)) return "";
        StringBuilder sb = new StringBuilder();
        bool first = true;
        foreach (char c in grapheme) {
            if (!first) sb.Append("  +  ");
            first = false;
            int cp = (int)c;
            sb.Append("U+");
            sb.Append(cp.ToString("X4"));
            string name;
            if (NameMap.TryGetValue(cp, out name)) { sb.Append(" "); sb.Append(name); }
            else { sb.Append(" "); sb.Append(ScriptOf(c)); }
            string baseLetter;
            if (Inverse.TryGetValue(c, out baseLetter) && baseLetter[0] != c) {
                sb.Append("  [from ");
                sb.Append(baseLetter);
                sb.Append("]");
            }
        }
        return sb.ToString();
    }

    static string ScriptOf(char c) {
        if (c >= '\u0600' && c <= '\u06FF') return "Arabic";
        if (c >= '\u0590' && c <= '\u05FF') return "Hebrew";
