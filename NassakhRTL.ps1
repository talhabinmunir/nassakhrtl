public class FixOptions {
    public bool WesternDigits = true;
    public bool RemoveZeroWidth = true;
    public bool RemoveDiacritics = false;
    public bool RemoveTatweel = false;
    public bool PunctToLatin = false;
    public bool NormalizeAlef = false;
    public bool NormalizeYaTa = false;
    // 0 = off. When > 0, long logical lines are hard-broken at word
    // boundaries BEFORE conversion. Without this, a wrapping paragraph
    // pasted into Affinity re-wraps the reversed string and the line
    // order comes out bottom-to-top.
    public int WrapWidth = 0;

    // serialize to/from a 7-char bit string for settings/presets
    public string ToBits() {
        char[] b = new char[7];
        b[0] = WesternDigits ? '1' : '0';
        b[1] = RemoveZeroWidth ? '1' : '0';
        b[2] = RemoveDiacritics ? '1' : '0';
        b[3] = RemoveTatweel ? '1' : '0';
        b[4] = PunctToLatin ? '1' : '0';
        b[5] = NormalizeAlef ? '1' : '0';
        b[6] = NormalizeYaTa ? '1' : '0';
        return new string(b);
    }
    public static FixOptions FromBits(string s) {
        FixOptions o = new FixOptions();
        if (s == null || s.Length < 7) return o;
        o.WesternDigits = s[0] == '1';
        o.RemoveZeroWidth = s[1] == '1';
        o.RemoveDiacritics = s[2] == '1';
        o.RemoveTatweel = s[3] == '1';
        o.PunctToLatin = s[4] == '1';
        o.NormalizeAlef = s[5] == '1';
        o.NormalizeYaTa = s[6] == '1';
        return o;
    }
}

