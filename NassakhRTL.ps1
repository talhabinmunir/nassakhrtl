    static Dictionary<char, string> BuildInverse() {
        Dictionary<char, string> d = new Dictionary<char, string>();
        foreach (KeyValuePair<char, char[]> kv in Forms) {
            foreach (char f in kv.Value) {
                if (f != '\0' && !d.ContainsKey(f)) d[f] = kv.Key.ToString();
            }
        }
        foreach (KeyValuePair<char, char[]> kv in LamAlef) {
            foreach (char f in kv.Value) d[f] = "\u0644" + kv.Key.ToString();
        }
        return d;
    }

    public static bool IsTransparent(char c) {
        return (c >= '\u0610' && c <= '\u061A')
            || (c >= '\u064B' && c <= '\u065F')
            || c == '\u0670'
            || (c >= '\u06D6' && c <= '\u06DC')
            || (c >= '\u06DF' && c <= '\u06E4')
            || c == '\u06E7' || c == '\u06E8'
            || (c >= '\u06EA' && c <= '\u06ED')
            || (c >= '\u08D3' && c <= '\u08FF')
            || (c >= '\u0591' && c <= '\u05C7');
    }

    public static string Reshape(string text, out int count) {
        char[] chars = text.ToCharArray();
        StringBuilder sb = new StringBuilder();
        bool prevCapable = false;
        count = 0;
        int i = 0;
        while (i < chars.Length) {
            char ch = chars[i];
            if (IsTransparent(ch)) { sb.Append(ch); i++; continue; }
            char[] f;
            if (!Forms.TryGetValue(ch, out f)) { sb.Append(ch); prevCapable = false; i++; continue; }

            if (ch == '\u0644') {
                int j = i + 1;
                StringBuilder between = new StringBuilder();
                while (j < chars.Length && IsTransparent(chars[j])) { between.Append(chars[j]); j++; }
                char[] lig;
                if (j < chars.Length && LamAlef.TryGetValue(chars[j], out lig)) {
                    sb.Append(prevCapable ? lig[1] : lig[0]);
                    sb.Append(between.ToString());
                    count++;
                    prevCapable = false;
                    i = j + 1;
                    continue;
                }
            }

            int k = i + 1;
            while (k < chars.Length && IsTransparent(chars[k])) k++;
            bool nextJoinable = k < chars.Length && Forms.ContainsKey(chars[k]) && chars[k] != '\u0621';
            bool capable = f[2] != '\0';
            bool linkedBefore = prevCapable && f[1] != '\0' && ch != '\u0621';
            bool linkedAfter = capable && nextJoinable;
            char shaped = linkedBefore ? (linkedAfter ? f[3] : f[1]) : (linkedAfter ? f[2] : f[0]);
            if (shaped == '\0') shaped = f[0];
            if (shaped != ch) count++;
            sb.Append(shaped);
            prevCapable = capable;
            i++;
        }
        return sb.ToString();
    }

