    static Dictionary<int, string> BuildNames() {
        Dictionary<int, string> d = new Dictionary<int, string>();
        foreach (string row in UniNames.Table) {
            int bar = row.IndexOf('|');
            d[System.Convert.ToInt32(row.Substring(0, bar), 16)] = row.Substring(bar + 1);
