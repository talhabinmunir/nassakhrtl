public class PreviewPanel : Panel {
    string text = "";
    List<Rectangle> boxes = new List<Rectangle>();
    List<string> glyphs = new List<string>();
    public Theme Th = Theme.Light();
    public delegate void GlyphHandler(string g);
    public event GlyphHandler GlyphPicked;
    Font arial = new Font("Arial", 15F);

    public PreviewPanel() {
        DoubleBuffered = true;
        AutoScroll = true;
        SetStyle(ControlStyles.ResizeRedraw, true);
    }

    public void SetText(string t) {
        text = t == null ? "" : t;
        Invalidate();
    }

    protected override void OnPaint(PaintEventArgs e) {
        base.OnPaint(e);
        Graphics g = e.Graphics;
        g.Clear(Th.PreviewBg);
        g.TextRenderingHint = System.Drawing.Text.TextRenderingHint.AntiAlias;
        boxes.Clear(); glyphs.Clear();
        StringFormat sf = (StringFormat)StringFormat.GenericTypographic.Clone();
        sf.FormatFlags |= StringFormatFlags.MeasureTrailingSpaces;
        float lineH = arial.GetHeight(g) + 6f;
        float y = 8f + AutoScrollPosition.Y;
        float maxW = 0f;
        string[] lines = text.Replace("\r\n", "\n").Split('\n');
        using (Brush br = new SolidBrush(Th.Text)) {
            foreach (string line in lines) {
                float x = 10f + AutoScrollPosition.X;
                foreach (string gr in Engine.Graphemes(line)) {
                    SizeF sz = g.MeasureString(gr, arial, 1000, sf);
                    float w = sz.Width;
                    if (w < 2f) w = arial.Size * 0.45f;
                    g.DrawString(gr, arial, br, x, y, sf);
                    boxes.Add(new Rectangle((int)(x - AutoScrollPosition.X), (int)(y - AutoScrollPosition.Y), (int)w + 1, (int)lineH));
                    glyphs.Add(gr);
                    x += w;
                }
                if (x > maxW) maxW = x;
                y += lineH;
            }
        }
        AutoScrollMinSize = new Size((int)maxW + 20, (int)(y - AutoScrollPosition.Y) + 10);
    }

    protected override void OnMouseClick(MouseEventArgs e) {
        base.OnMouseClick(e);
        Point p = new Point(e.X - AutoScrollPosition.X, e.Y - AutoScrollPosition.Y);
        for (int i = 0; i < boxes.Count; i++) {
            if (boxes[i].Contains(p)) {
                if (GlyphPicked != null) GlyphPicked(glyphs[i]);
                return;
            }
        }
    }
}

