            foreach (KeyValuePair<string, string> kv in presets) sb.AppendLine("preset." + kv.Key + "=" + kv.Value);
            File.WriteAllText(SettingsFile, sb.ToString(), new UTF8Encoding(false));
        } catch (Exception) { }
    }

